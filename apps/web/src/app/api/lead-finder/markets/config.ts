export function getMarketByMetro(metro: string): WholesaleMarket | undefined {
  return TOP_WHOLESALE_MARKETS.find(m =>
    m.metro.toLowerCase() === metro.toLowerCase()
  );
}

export function getMarketsByState(stateCode: string): WholesaleMarket[] {
  return TOP_WHOLESALE_MARKETS.filter(m =>
    m.stateCode.toUpperCase() === stateCode.toUpperCase()
  );
}

export function getAllCounties(): string[] {
  return TOP_WHOLESALE_MARKETS.flatMap(m =>
    m.primaryCounties.map(c => `${c}, ${m.stateCode}`)
  );
}

export function getAllZips(): string[] {
  return TOP_WHOLESALE_MARKETS.flatMap(m => m.topZips);
}

export function getMarketStats() {
  const markets = TOP_WHOLESALE_MARKETS;
  return {
    totalMarkets: markets.length,
    totalCounties: markets.reduce((sum, m) => sum + m.primaryCounties.length, 0),
    totalZips: markets.reduce((sum, m) => sum + m.topZips.length, 0),
    states: [...new Set(markets.map(m => m.stateCode))],
    avgMedianPrice: Math.round(markets.reduce((sum, m) => sum + m.medianHomePrice, 0) / markets.length),
    avgWholesaleSpread: Math.round(markets.reduce((sum, m) => sum + m.avgWholesaleSpread, 0) / markets.length),
    avgDistressedPct: (markets.reduce((sum, m) => sum + m.distressedInventoryPct, 0) / markets.length).toFixed(1),
  };
}
