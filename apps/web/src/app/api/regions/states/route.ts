/**
 * States API
 *
 * GET /api/regions/states - List all US states with metadata
 */
import { NextRequest, NextResponse } from 'next/server';
import { auth } from '@/lib/auth';
import { headers } from 'next/headers';
import sql from '@/app/api/utils/sql';

export async function GET(request: NextRequest) {
  const session = await auth.api.getSession({ headers: await headers() });
  if (!session) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
  }

  try {
    // Get states from reference table with aggregated data
    const states = await sql`
      SELECT
        code,
        name,
        county_count,
        zip_count,
        population
      FROM state_reference
      ORDER BY name ASC
    `;

    // If reference table is empty, return static list
    if (states.length === 0) {
      return NextResponse.json(US_STATES_FALLBACK);
    }

    return NextResponse.json(states);
  } catch (error: any) {
    console.error('GET /api/regions/states error:', error);
    // Return fallback on error
    return NextResponse.json(US_STATES_FALLBACK);
  }
}

