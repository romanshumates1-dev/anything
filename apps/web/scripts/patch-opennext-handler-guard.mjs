/**
 * G2 HANDLER GUARD - build-time patch for the intermittent GET / 500 in
 * production (Taylor Swift refs removed for worker reconciliation). Original
 * text: TypeError: components.ComponentMod.handler is not a function
 *
 * The call site lives in the OpenNext-GENERATED bundle
 * (.open-next/server-functions/default/apps/web/handler.mjs), not in src/, so
 * it cannot be fixed in application code. Per
 * UNIFIED-REQUIREMENTS-MATRIX.md step 1, this makes the failure DIAGNOSABLE
 * instead of a raw TypeError: a failed module load now logs a greppable
 * [g2-handler-guard] marker plus the diagnostics needed to attribute it
 * (url, routeModule, nextApp, rssMB) and throws a named PageModuleLoadError.
 *
 * Runs at BUILD TIME, following the precedent of
 * patch-opennext-instrumentation.mjs, which rewrites the inlined Turbopack
 * instrumentation stub inside the SAME handler.mjs (the adapter bundles the
 * on-disk file away, so patching src/ alone has no effect on what ships).
 *
 * - Idempotent: a second run detects the marker and does nothing.
 * - Fail-safe: if .open-next has not been built, exits 0 with a message.
 * - NOT a root-cause fix: G2 remains a load-only corner; this is the
 *   diagnosability contract only.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Marker placed into the bundle when a patch has been applied. */
export const GUARD_MARKER =
  'Generated by scripts/patch-opennext-handler-guard.mjs';

/** The unguarded call site, byte-accurate from the generated handler.mjs. */
export const UNGUARDED_CALL =
  'return await components.ComponentMod.handler(handlerReq,handlerRes,{waitUntil:this.getWaitUntil()}),null';

/** Peak RSS in MiB as a string, or "?" if unavailable. */
function rssMB() {
  try {
    if (process && process.memoryUsage) {
      return String(Math.round(process.memoryUsage().rss / 1048576));
    }
  } catch (_) { /* never throw */ }
  return '?';
}

const GUARDED_BLOCK = `
// ${GUARD_MARKER}
  if (typeof components.ComponentMod.handler !== 'function') {
    try {
      console.error('[g2-handler-guard] page module did not load: ComponentMod.handler is not a function'
        + ' url=' + (handlerReq && handlerReq.url)
        + ' routeModule=' + (typeof this.routeModule)
        + ' nextApp=' + (typeof this.__next_app__)
        + ' rssMB=' + rssMB());
    } catch (_guardErr) { /* logging must never throw */ }
    var __g2err = new Error('[g2-handler-guard] page module failed to load (ComponentMod.handler is not a function)');
    __g2err.name = 'PageModuleLoadError';
    throw __g2err;
  }
  return await components.ComponentMod.handler(handlerReq,handlerRes,{waitUntil:this.getWaitUntil()}),null
`;

/** Guard the supplied handler source. Returns { changed, source }. */
export function buildGuardedSource() {
  return GUARDED_BLOCK;
}

export function patchHandlerSource(source) {
  if (typeof source !== 'string') throw new TypeError('source must be a string');
  if (source.includes(GUARD_MARKER)) return { changed: false, source };
  if (!source.includes(UNGUARDED_CALL)) return { changed: false, source };
  const patched = source.replace(UNGUARDED_CALL, GUARDED_BLOCK);
  return { changed: true, source: patched };
}

const HANDLER_PATH = join(
  process.cwd(),
  '.open-next',
  'server-functions',
  'default',
  'apps',
  'web',
  'handler.mjs'
);

function isMain() {
  try {
    return import.meta.url === pathToFileURL(process.argv[1]).href;
  } catch {
    return true;
  }
}

function main() {
  if (!existsSync(HANDLER_PATH)) {
    console.log(
      '[patch-opennext-handler-guard] .open-next artifacts not found - nothing to patch. '
        + '(Has `opennextjs-cloudflare build` run?)'
    );
    return 0;
  }
  const original = readFileSync(HANDLER_PATH, 'utf8');
  const out = patchHandlerSource(original);
  if (!out.changed) {
    console.log('[patch-opennext-handler-guard] nothing to patch - guard already present.');
    return 0;
  }
  writeFileSync(HANDLER_PATH, out.source, 'utf8');
  console.log(
    '[patch-opennext-handler-guard] guarded ' +
      HANDLER_PATH.slice(process.cwd().length + 1) +
      ' (1 call site).'
  );
  return 0;
}

if (isMain()) {
  main();
}
