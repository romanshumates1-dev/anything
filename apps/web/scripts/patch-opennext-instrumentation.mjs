#!/usr/bin/env node
/**
 * Repairs the Turbopack instrumentation stub that `next build` emits, so the
 * Cloudflare Worker bundle can actually load it.
 *
 * THE PROBLEM (verified against adapter 1.20.6, current latest)
 * Next 16 (Turbopack) emits `.next/server/instrumentation.js` as a runtime
 * stub:
 *
 *     var R=require("./chunks/[turbopack]_runtime.js")("server/instrumentation.js")
 *     R.c("server/chunks/[root-of-the-server]__<hash>._.js")
 *     R.m(<module-id>)
 *     module.exports=R.m(<module-id>).exports
 *
 * The chunk it names contains the compiled register(). Next ALSO traces the
 * chunk in `instrumentation.js.nft.json`, but `@opennextjs/cloudflare`'s copy
 * step does not carry it into
 * `.open-next/server-functions/default/apps/web/.next/server/chunks/`
 * (verified: present in `.next`, absent in `.open-next`). The adapter's
 * `requireChunk` switch is therefore generated without a case for it, and at
 * runtime the chain is:
 *
 *     instrumentation.js stub → R.c("<missing chunk>") → requireChunk default
 *       → throw "Not found" (no .code property) → external-module catch
 *         rethrows (err.code !== 'MODULE_NOT_FOUND') → "Failed to prepare
 *         server" → EVERY route 500s, including /api/system/health.
 *
 * Upstream has no fix at 1.20.6 (their patchInstrumentation plugin targets a
 * different shape and does not fire for this build).
 *
 * THE FIX
 * Replace the stub with a self-contained CommonJS module that exports the
 * SAME register() behaviour as `src/instrumentation.ts` — boot-time env
 * validation, non-throwing on Cloudflare Workers, soft-warns optional vars.
 * The compiled chunk's only other content is a LAZY require of `ws` (from
 * `lib/websocket.ts`) that register() never evaluates, so inlining register()
 * loses nothing.
 *
 * ⚠ KEEP-IN-SYNC: the register() below mirrors `src/instrumentation.ts`
 * (HARD_REQUIRED / SOFT_RECOMMENDED / workerd-aware no-throw). If you edit the
 * source file, update this stub in the same change. The src file remains the
 * canonical version for dev/Docker/Vercel; this stub exists only because the
 * adapter cannot load the Turbopack chunk on Workers.
 *
 * The `NEXT_RUNTIME !== 'nodejs'` guard from the source is deliberately NOT
 * reproduced: Next inlines that constant to `true` in this (nodejs) build, so
 * the compiled chunk has no guard — this stub matches the compiled behaviour.
 *
 * Idempotent: a second run detects the self-contained stub and does nothing.
 * Fail-safe if `.open-next` is absent (build has not run).
 *
 * Usage (wired into `cf:build`, after scrub-opennext-env.mjs):
 *   node scripts/patch-opennext-instrumentation.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const STUB_PATH = join(
  process.cwd(),
  '.open-next',
  'server-functions',
  'default',
  'apps',
  'web',
  '.next',
  'server',
  'instrumentation.js',
);

// The adapter's bundler INLINES the stub above into the app handler as a
// __commonJS module (verified: `var require_instrumentation=__commonJS({...}});`
// inside apps/web/handler.mjs). Patching the on-disk file alone therefore has
// no effect on the final Worker bundle — the inlined copy must be rewritten
// too. This is the minified shape the bundler emits for the Turbopack stub:
// it always ends with `R.m(<id>);module.exports=R.m(<id>).exports`, which the
// regex anchors on so it cannot over-match into adjacent modules.
const HANDLER_PATH = join(
  process.cwd(),
  '.open-next',
  'server-functions',
  'default',
  'apps',
  'web',
  'handler.mjs',
);
const INLINED_STUB_RE =
  /var require_instrumentation=__commonJS\(\{"[^"]+"\(exports,module\)\{[\s\S]*?R\.m\(\d+\);module\.exports=R\.m\(\d+\)\.exports\}\}\);/;

const SELF_CONTAINED_STUB = `"use strict";
// Generated by scripts/patch-opennext-instrumentation.mjs — DO NOT EDIT BY HAND.
// Self-contained replacement for the Turbopack instrumentation stub (see the
// script header for why). Mirrors src/instrumentation.ts register().
const HARD_REQUIRED = ["DATABASE_URL", "BETTER_AUTH_SECRET"];
const SOFT_RECOMMENDED = [
  "TWILIO_ACCOUNT_SID",
  "TWILIO_AUTH_TOKEN",
  "ANTHROPIC_API_KEY",
  "STRIPE_SECRET_KEY",
  "LEGAL_ENTITY_NAME",
  "SUPPORT_EMAIL",
];
const isCloudflareWorkers =
  typeof navigator !== "undefined" && navigator.userAgent === "Cloudflare-Workers";
async function register() {
  const missing = HARD_REQUIRED.filter((name) => !process.env[name]);
  if (missing.length > 0) {
    console.error(
      \`\\n[boot] FATAL: missing required environment variable(s): \${missing.join(", ")}\\n\` +
        \`[boot] The app cannot start without these.\\n\`
    );
    if (isCloudflareWorkers) {
      console.error(
        \`[boot] Running on Cloudflare Workers — continuing instead of throwing so the\\n\` +
          \`[boot] health probe stays reachable. Set these via \\\`wrangler secret put\\\`.\\n\`
      );
      return;
    }
    throw new Error(\`Missing required environment variables: \${missing.join(", ")}\`);
  }
  const unset = SOFT_RECOMMENDED.filter((name) => !process.env[name]);
  if (unset.length > 0) {
    console.warn(
      \`[boot] NOTE: \${unset.join(", ")} not set — related features run in mock/degraded mode.\`
    );
  }
}
module.exports = { register };
`;

const MARKER = 'Generated by scripts/patch-opennext-instrumentation.mjs';

if (!existsSync(STUB_PATH) && !existsSync(HANDLER_PATH)) {
  console.log(
    '[patch-opennext-instrumentation] .open-next artifacts not found — nothing to patch. ' +
      '(Has `opennextjs-cloudflare build` run?)'
  );
  process.exit(0);
}

let patchTarget = null;

// --- 1. On-disk stub (covers bundles that import the file instead of inlining) ---
if (existsSync(STUB_PATH)) {
  const original = readFileSync(STUB_PATH, 'utf8');
  if (original.includes(MARKER)) {
    console.log('[patch-opennext-instrumentation] On-disk stub already patched.');
  } else {
    const chunkRef = original.match(/R\.c\("([^"]+)"\)/);
    if (!chunkRef) {
      console.log(
        '[patch-opennext-instrumentation] On-disk stub is not the expected Turbopack shape — leaving it unchanged.'
      );
    } else {
      writeFileSync(STUB_PATH, SELF_CONTAINED_STUB, 'utf8');
      patchTarget = chunkRef[1];
      console.log(
        `[patch-opennext-instrumentation] Replaced on-disk Turbopack stub ` +
          `(was loading "${chunkRef[1]}") with a self-contained register().`
      );
    }
  }
}

// --- 2. Inlined copy inside the app handler (the one the Worker actually ships) ---
if (existsSync(HANDLER_PATH)) {
  const handler = readFileSync(HANDLER_PATH, 'utf8');
  if (handler.includes(MARKER)) {
    console.log('[patch-opennext-instrumentation] Inlined handler stub already patched.');
  } else {
    const m = handler.match(INLINED_STUB_RE);
    if (!m) {
      console.log(
        '[patch-opennext-instrumentation] No inlined Turbopack stub found in handler.mjs — nothing to do.'
      );
    } else {
      const chunkRef = m[0].match(/R\.c\("([^"]+)"\)/);
      const key = m[0].match(/"([^"]+)"/)?.[1] ?? 'instrumentation';
      // Function replacement: the stub contains `${...}` template text that a
      // string replacement would treat as `$`-patterns.
      const replacement =
        `var require_instrumentation=__commonJS({"${key}"(exports,module){` +
        SELF_CONTAINED_STUB +
        '}});';
      writeFileSync(HANDLER_PATH, handler.replace(m[0], () => replacement), 'utf8');
      patchTarget = patchTarget ?? chunkRef?.[1] ?? null;
      console.log(
        '[patch-opennext-instrumentation] Replaced the INLINED Turbopack stub in ' +
          'apps/web/handler.mjs with a self-contained register()' +
          (chunkRef ? ` (was loading "${chunkRef[1]}").` : '.')
      );
    }
  }
}

if (patchTarget) {
  console.log(
    '[patch-opennext-instrumentation] NOTE: src/instrumentation.ts is still canonical for ' +
      'dev/Docker/Vercel. Keep the two in sync (see the script header).'
  );
}
console.log('[patch-opennext-instrumentation] done.');
